"""
Service contracts — what each service OFFERS and what it CALLS on other services.

Extracted from source with tree-sitter (no running system needed):

Offers
  http   Spring @Get/Post/.../RequestMapping (+ class-level prefix), Express
         app.get("/x"), Go net/http HandleFunc, gorilla mux .Methods().Path(),
         gin/echo/chi r.GET("/x"), FastAPI/Flask decorators
  grpc   server implementations of services declared in .proto files
         (Go RegisterXServer + methods, Python XServicer, Java XImplBase,
         Node addService(X.service, {...}))
  queue  consumers: @RabbitListener / @KafkaListener / @SqsListener,
         subscribe / consume / basic_consume / setQueueNames

Calls
  http   any call that is passed a URL. URLs are *evaluated*: string literals,
         concatenation, template strings, f-strings, util.format / fmt.Sprintf /
         String.format, and constants, config-object properties and URL-building
         methods defined anywhere in the same service. So wrappers such as
         helpers.simpleHttpRequest(endpoints.cartsUrl + "/items") work without
         knowing the wrapper. The URL host is matched to a service name.
  grpc   stub calls: pb.NewXClient(conn).M(...), XStub(channel).M(...), ...
  queue  producers: convertAndSend / KafkaTemplate.send / producer.send /
         basic_publish / send_message ...

Every record is attached to the indexed chunk (function/method) containing it.
"""
