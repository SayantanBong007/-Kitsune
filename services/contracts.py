@dataclass
class Offer:
    service: str
    kind: str          # http | grpc | queue
    method: str        # HTTP verb / ANY, rpc name, or "consume"
    path: str          # normalized HTTP path, "pkg.Service/Method", or topic
    file: str
    line: int
    node_id: str = ""
    symbol: str = ""
    prefix: bool = False   # HTTP path prefix route (gorilla PathPrefix, catch-all)


@dataclass
class Call:
    service: str
    kind: str
    method: str
    path: str          # normalized path, "pkg.Service/Method", or topic ("" if unknown)
    target: str        # target service name, "" if not determined
    file: str
    line: int
    node_id: str = ""
    symbol: str = ""
    raw: str = ""      # evaluated URL / expression, for explanations


@dataclass
class ServiceContracts:
    offers: list[Offer] = field(default_factory=list)
    calls: list[Call] = field(default_factory=list)

    def to_dict(self) -> dict:
        return {"offers": [asdict(o) for o in self.offers], "calls": [asdict(c) for c in self.calls]}


def _key(path: str) -> str:
    return os.path.normcase(os.path.abspath(str(path)))


# ── Paths and URLs ────────────────────────────────────────────────────────────

_PARAM = re.compile(r"\{[^}]*\}|:[A-Za-z_]\w*|<[^>]+>|\*+")
# Literal IDs in example URLs: hex object ids, UUIDs
_ID_SEGMENT = re.compile(r"^([0-9a-f]{12,}|[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})$", re.I)


def normalize_path(path: str) -> str:
    """'/carts/{customerId:.*}/items/' → '/carts/{*}/items'; query strings dropped."""
    path = path.split("?")[0].split("#")[0].strip()
    if not path.startswith("/"):
        path = "/" + path
    segments = []
    for seg in path.split("/"):
        if not seg:
            continue
        seg = _PARAM.sub("{*}", seg)
        if "{*}" in seg or seg.isdigit() or _ID_SEGMENT.match(seg):
            seg = "{*}"
        segments.append(seg)
    return "/" + "/".join(segments)


# Public top-level domains. Service DNS names (cart, cart.default.svc.cluster.local,
# cart.internal) never end in one of these.
_PUBLIC_TLDS = {"com", "org", "net", "io", "dev", "ai", "co", "app", "cloud", "gov", "edu",
                "info", "biz", "me", "tech", "xyz", "us", "uk", "de", "fr", "in", "jp", "cn",
                "ru", "br", "au", "ca", "eu", "nl", "se", "ch", "es", "it", "kr", "sg"}


def _is_public_host(host: str) -> bool:
    labels = host.split(".")
    return len(labels) >= 2 and labels[-1] in _PUBLIC_TLDS and "{*}" not in host


def parse_url(template: str, hosts: dict[str, str]) -> tuple[str, str, bool]:
    """(target_service, normalized_path, looks_like_url) for an evaluated URL template.

    `hosts` maps lower-cased host aliases to service names.
    """
    t = template.strip()
    if not t:
        return "", "", False
    scheme = re.match(r"^[a-z][a-z0-9+.-]*://", t, re.I)
    rest = t[scheme.end():] if scheme else t
    target, path = "", ""
    if scheme or not rest.startswith("/"):
        host, _, tail = rest.partition("/")
        host_name = re.split(r"\{\*\}|:|%", host)[0].lower().strip(".")
        if _is_public_host(host_name):
            return "", "", False   # api.github.com: a third-party API, not one of our services
        host_name = host_name.split(".")[0] if host_name else ""
        target = hosts.get(host_name, "")
        if not scheme and not tail:
            return "", "", False   # a bare word that happens to equal a service name
        if scheme or target:
            # "http://catalogue{*}" + req.url: the path is only known at runtime
            path = "/" + tail if tail else ("" if "{*}" in host else "/")
        else:
            return "", "", False
    else:
        path = rest
    looks = bool(scheme or target or path.startswith("/"))
    return target, (normalize_path(path) if path else ""), looks


def paths_match(call_path: str, offer_path: str, prefix: bool) -> int:
    """Match score (higher = more literal segments equal); -1 if no match."""
    c = [s for s in call_path.split("/") if s]
    o = [s for s in offer_path.split("/") if s]
    if prefix:
        if len(c) < len(o):
            return -1
        c = c[:len(o)]
    elif len(c) != len(o):
        return -1
    score = 0
    for cs, os_ in zip(c, o):
        if cs == "{*}" and os_ == "{*}":
            score += 1          # parameter lines up with parameter
        elif cs == "{*}" or os_ == "{*}":
            score += 0          # a wildcard matches, but is no evidence
        elif cs == os_:
            score += 2
        else:
            return -1
    return score


# ── Source access helpers ─────────────────────────────────────────────────────

class _File:
    def __init__(self, path: Path, service: str):
        self.path = path
        self.key = _key(path)
        self.service = service
        self.ext = path.suffix
        self.source = path.read_bytes()
        self.tree = make_parser(self.ext).parse(self.source)
        self.root = self.tree.root_node

    def text(self, node) -> str:
        return self.source[node.start_byte:node.end_byte].decode("utf-8", errors="replace") \
            if node is not None else ""


def _walk(node):
    stack = [node]
    while stack:
        n = stack.pop()
        yield n
        stack.extend(reversed(n.children))


def _last_name(text: str) -> str:
    text = re.sub(r"\s+", "", text)                 # chains split across lines
    text = re.sub(r"\(.*\)$", "", text)
    return re.split(r"[.\->:]+", text)[-1] if text else ""


# ── The extractor ─────────────────────────────────────────────────────────────

class ContractExtractor:
    """Extracts offers and calls for all services of one system."""

    def __init__(self, services: dict[str, Path], symbols: dict[str, list[tuple]] | None = None):
        """
        services: {service_name: path}
        symbols:  {normalized file path: [(start_line, end_line, node_id, qualified_name)]}
                  — the indexed chunks, used to attach records to functions.
        """
        self.services = {name: Path(p) for name, p in services.items()}
        self.symbols = symbols or {}
        self.hosts: dict[str, str] = {}
        for name, path in self.services.items():
            for alias in service_aliases(name, path):
                self.hosts.setdefault(alias, name)
        self.files: dict[str, list[_File]] = {}
        self.constants: dict[str, dict[str, list[tuple[_File, object]]]] = {}
        self.protos: dict[str, list[str]] = {}       # "pkg.Service" → [rpc, ...]
        self.proto_by_short: dict[str, str] = {}     # "Service" → "pkg.Service"

    # ── loading ──────────────────────────────────────────────────────────

    def _source_files(self, root: Path):
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = [d for d in dirnames if d not in _SKIP_DIRS and not d.startswith(".")]
            for fn in filenames:
                p = Path(dirpath) / fn
                rel = p.relative_to(root).as_posix()
                if p.suffix in SUPPORTED_EXTENSIONS and not _TEST_DIR.search(rel) \
                        and not _ASSET_DIR.search(rel) and not _GENERATED_FILE.search(fn):
                    yield p

    def load(self):
        for name, root in self.services.items():
            files = []
            for p in self._source_files(root):
                try:
                    f = _File(p, name)
                except Exception:
                    continue
                if _GENERATED_MARK.search(f.source[:2000]):
                    continue
                files.append(f)
            self.files[name] = files
            self.constants[name] = self._collect_constants(files)
        self._load_protos()
        return self

    def _load_protos(self):
        roots = {p for p in self.services.values()}
        common = Path(os.path.commonpath([str(p) for p in roots])) if roots else None
        search = [common] if common else []
        seen = set()
        for base in search:
            for proto in base.rglob("*.proto"):
                if any(part in _SKIP_DIRS for part in proto.parts) or proto in seen:
                    continue
                seen.add(proto)
                text = proto.read_text(encoding="utf-8", errors="ignore")
                pkg = (re.search(r"^\s*package\s+([\w.]+)\s*;", text, re.M) or [None, ""])[1]
                for svc, body in re.findall(r"service\s+(\w+)\s*\{(.*?)\n\}", text, re.S):
                    full = f"{pkg}.{svc}" if pkg else svc
                    rpcs = re.findall(r"\brpc\s+(\w+)\s*\(", body)
                    self.protos.setdefault(full, [])
                    self.protos[full] += [r for r in rpcs if r not in self.protos[full]]
                    self.proto_by_short.setdefault(svc, full)

    # ── constants & evaluation ───────────────────────────────────────────

    def _collect_constants(self, files: list[_File]) -> dict[str, list]:
        consts: dict[str, list] = {}

        def put(name: str, f: _File, value, kind: str = "var"):
            # kind: var (variable/constant), prop (object property), method (return
            # value of a URL-building method), field (set via a constructor argument)
            if name and value is not None:
                consts.setdefault(name, []).append((f, value, kind))

        for f in files:
            for n in _walk(f.root):
                t = n.type
                if t == "variable_declarator":                      # JS/TS/Java
                    put(f.text(n.child_by_field_name("name")), f, n.child_by_field_name("value"))
                elif t == "pair":                                    # JS object property
                    key = f.text(n.child_by_field_name("key")).strip("'\"`")
                    put(key, f, n.child_by_field_name("value"), "prop")
                elif t in ("assignment", "assignment_expression"):   # Python / JS
                    left = n.child_by_field_name("left")
                    kind = "prop" if left is not None and left.type in (
                        "member_expression", "attribute", "field_access") else "var"
                    put(_last_name(f.text(left)), f, n.child_by_field_name("right"), kind)
                elif t in ("const_spec", "var_spec"):                # Go
                    names = [c for c in n.children if c.type == "identifier"]
                    value = n.child_by_field_name("value")
                    if names and value is not None and value.named_children:
                        put(f.text(names[0]), f, value.named_children[0])
                elif t in ("method_declaration", "function_declaration", "function_definition"):
                    # URL-building methods: getPaymentUri() { return new ServiceUri(...) }
                    name = f.text(n.child_by_field_name("name"))
                    body = n.child_by_field_name("body")
                    if name and body is not None:
                        for r in _walk(body):
                            if r.type == "return_statement" and r.named_children:
                                put(name, f, r.named_children[0], "method")
                                break
        self._constructor_flow(files, put)
        return consts

    def _constructor_flow(self, files: list[_File], put):
        """Values passed to constructors reach the fields they initialise:
        new CartHelper(CART_URL) + CartHelper(String baseUrl) { this.baseUrl = baseUrl; }
        → baseUrl = CART_URL. (Java, JS/TS, Python __init__.)"""
        params_to_fields: dict[str, dict[int, list[str]]] = {}
        for f in files:
            for n in _walk(f.root):
                cls, ctor = None, None
                if n.type == "constructor_declaration":                       # Java
                    cls, ctor = f.text(n.child_by_field_name("name")), n
                elif n.type == "method_definition" and f.text(n.child_by_field_name("name")) == "constructor":
                    p = n.parent.parent if n.parent is not None else None      # JS class body → class
                    cls = f.text(p.child_by_field_name("name")) if p is not None else None
                    ctor = n
                elif n.type == "function_definition" and f.text(n.child_by_field_name("name")) == "__init__":
                    p = n.parent.parent if n.parent is not None else None      # Python
                    cls = f.text(p.child_by_field_name("name")) if p is not None else None
                    ctor = n
                if not cls or ctor is None:
                    continue
                plist = ctor.child_by_field_name("parameters")
                names = []
                for p in (plist.named_children if plist is not None else []):
                    ident = p.child_by_field_name("name") or p.child_by_field_name("pattern") or p
                    text = f.text(ident).split("=")[0].split(":")[0].strip()
                    if text not in ("self", "cls") and re.match(r"^[A-Za-z_]\w*$", text):
                        names.append(text)
                index = {name: i for i, name in enumerate(names)}
                mapping: dict[int, list[str]] = {}
                for a in _walk(ctor):
                    if a.type in ("assignment_expression", "assignment"):
                        left, right = a.child_by_field_name("left"), a.child_by_field_name("right")
                        lt, rt = f.text(left), f.text(right)
                        if re.match(r"^(this|self)\.\w+$", lt) and rt in index:
                            mapping.setdefault(index[rt], []).append(lt.split(".")[1])
                if mapping:
                    params_to_fields.setdefault(cls, {}).update(mapping)
        if not params_to_fields:
            return
        sites: dict[str, list] = {}
        for f in files:
            for n in _walk(f.root):
                if n.type in ("object_creation_expression", "new_expression"):
                    cls = _last_name(f.text(n.child_by_field_name("type") or n.child_by_field_name("constructor")))
                elif n.type == "call":
                    cls = _last_name(f.text(n.child_by_field_name("function")))
                else:
                    continue
                if cls in params_to_fields:
                    sites.setdefault(cls, []).append((f, n))
        for cls, where in sites.items():
            # Only when the class is built in exactly one place: with several
            # sites (new ServiceUri("payment"...), new ServiceUri("shipping"...))
            # a field's value depends on the instance, so it stays unknown here
            # and the site itself is evaluated instead.
            if len(where) != 1:
                continue
            f, n = where[0]
            args = self._args(n)
            for i, fields in params_to_fields[cls].items():
                if i < len(args):
                    for field_name in fields:
                        put(field_name, f, args[i], "field")

    def evaluate(self, service: str, f: _File, node, depth: int = 0, seen=None) -> str:
        """Best-effort string value of an expression; unknown parts become {*}."""
        if node is None or depth > 8:
            return "{*}"
        seen = seen or set()
        t = node.type
        if t in _STRING_TYPES:
            parts = []
            named = [c for c in node.children if c.type in _STRING_PARTS | _SUBST_TYPES]
            if not named:
                return f.text(node).strip("'\"`")
            for c in named:
                parts.append("{*}" if c.type in _SUBST_TYPES else f.text(c))
            return "".join(parts)
        if t == "boolean_operator" or (t == "binary_expression" and node.child_by_field_name("operator")
                                        is not None and f.text(node.child_by_field_name("operator"))
                                        in ("||", "??")):
            # process.env.CATALOGUE_HOST || 'catalogue' / os.environ.get(...) or 'user':
            # the configured value is unknown, the default names the service
            left = self.evaluate(service, f, node.child_by_field_name("left"), depth + 1, seen)
            right = self.evaluate(service, f, node.child_by_field_name("right"), depth + 1, seen)
            return left if left.replace("{*}", "") else right
        if t in ("binary_expression", "binary_operator"):
            op = node.child_by_field_name("operator")
            if op is not None and f.text(op) == "%":       # Python "http://%s/x" % host
                fmt = self.evaluate(service, f, node.child_by_field_name("left"), depth + 1, seen)
                return re.sub(r"%[-+ #0-9.]*[sdrfx]", "{*}", fmt)
            if op is not None and f.text(op) not in ("+",):
                return "{*}"
            return (self.evaluate(service, f, node.child_by_field_name("left"), depth + 1, seen)
                    + self.evaluate(service, f, node.child_by_field_name("right"), depth + 1, seen))
        if t in ("parenthesized_expression", "expression_statement", "await_expression"):
            inner = node.named_children[0] if node.named_children else None
            return self.evaluate(service, f, inner, depth + 1, seen)
        if t in ("call_expression", "call", "method_invocation", "object_creation_expression",
                 "new_expression"):
            return self._evaluate_call(service, f, node, depth, seen)
        if t in ("member_expression", "attribute", "subscript", "subscript_expression") and \
                re.match(r"(process\.env|os\.environ|ENV)\b", f.text(node)):
            var = re.findall(r"[A-Z][A-Z0-9_]+", f.text(node))
            return self._env_host(var[-1]) if var else "{*}"
        if t in ("identifier", "member_expression", "field_access", "selector_expression",
                 "attribute", "property_identifier", "field_identifier"):
            name = _last_name(f.text(node))
            if t == "identifier":
                if self._is_parameter(f, node, name):
                    return "{*}"     # a function parameter: its value comes from the caller
                local = not _CONSTANT_NAME.match(name)
                # plain locals (`id`, `custId`): variables from this file only
                return self._lookup(service, name, depth, seen,
                                    only_file=f if local else None, bare=True)
            return self._lookup(service, name, depth, seen)
        return "{*}"

    def _lookup(self, service: str, name: str, depth: int, seen: set, only_file=None,
                bare: bool = False) -> str:
        if not name or name in seen:
            return "{*}"
        verb = re.fullmatch(r"(?:Method)?(Get|Post|Put|Delete|Patch|Head|GET|POST|PUT|DELETE|PATCH)", name)
        if verb and name not in self.constants.get(service, {}):
            return verb.group(1).upper()
        candidates = self.constants.get(service, {}).get(name) or []
        if bare:
            # A bare identifier is a variable, never some object's property; a
            # local one only from its own file, a constructor-set field from anywhere.
            candidates = [c for c in candidates
                          if c[2] == "field" or (c[2] in ("var", "method")
                                                 and (only_file is None or c[0] is only_file))]
        elif only_file is not None:
            candidates = [c for c in candidates if c[0] is only_file]
        if not candidates:
            return "{*}"
        values = [self.evaluate(service, cf, value, depth + 1, seen | {name})
                  for cf, value, _ in candidates[:4]]
        # Prefer a value that actually carries information
        values.sort(key=lambda v: (v.count("{*}"), -len(v)))
        return values[0]

    def _is_parameter(self, f: _File, node, name: str) -> bool:
        """Is `name` a parameter of the function enclosing `node`?"""
        p = node.parent
        while p is not None:
            if p.type in ("function_declaration", "function_definition", "method_declaration",
                          "method_definition", "arrow_function", "function_expression", "function",
                          "constructor_declaration", "lambda", "func_literal"):
                params = p.child_by_field_name("parameters")
                if params is None:
                    params = next((c for c in p.children if c.type in
                                   ("formal_parameters", "parameters", "parameter_list")), None)
                if params is not None and re.search(rf"\b{re.escape(name)}\b", f.text(params)):
                    return True
            p = p.parent
        return False

    def _env_host(self, var: str) -> str:
        """CART_HOST / USER_SERVICE_ADDR / CATALOGUE_URL → a service alias, else unknown."""
        base = re.sub(r"(_SERVICE)?_(HOST|HOSTNAME|ADDR|ADDRESS|URL|URI|ENDPOINT|SVC|SERVICE)$", "",
                      var.upper())
        for cand in (base.lower().replace("_", "-"), base.lower().replace("_", ""),
                     base.lower().replace("_", "-") + "-service", base.lower().replace("_", "") + "service"):
            if cand in self.hosts:
                return cand
        return "{*}"

    def _args(self, node):
        args = node.child_by_field_name("arguments")
        return [a for a in (args.named_children if args is not None else [])
                if a.type not in ("comment",)]

    def _evaluate_call(self, service, f, node, depth, seen) -> str:
        fn = node.child_by_field_name("function") or node.child_by_field_name("name") \
            or node.child_by_field_name("constructor") or node.child_by_field_name("type")
        fname = _last_name(f.text(fn)) if fn is not None else ""
        args = self._args(node)
        if fname in ("getenv", "Getenv", "getProperty", "get", "getOrDefault", "env", "LookupEnv") \
                and args and re.search(r"(env|environ|System|process|config|getenv)", f.text(fn) or "", re.I):
            # getenv("CART_ENDPOINT", "cart") → the default; getenv("CART_HOST") → by name
            if len(args) >= 2:
                return self.evaluate(service, f, args[1], depth + 1, seen)
            var = self.evaluate(service, f, args[0], depth + 1, seen)
            return self._env_host(var) if var and "{*}" not in var else "{*}"
        if fname == "format" and fn is not None and fn.type == "attribute":
            obj = fn.child_by_field_name("object")
            if obj is not None and obj.type == "string":
                # Python 'http://{user}:8080/x/{id}'.format(user=USER, id=id)
                template = self.evaluate(service, f, obj, depth + 1, seen)
                kwargs = {f.text(a.child_by_field_name("name")): a.child_by_field_name("value")
                          for a in args if a.type == "keyword_argument"}
                positional = [a for a in args if a.type != "keyword_argument"]

                def fill(m):
                    key = m.group(1)
                    if key in kwargs:
                        return self.evaluate(service, f, kwargs[key], depth + 1, seen)
                    if key.isdigit() and int(key) < len(positional):
                        return self.evaluate(service, f, positional[int(key)], depth + 1, seen)
                    return "{*}"
                return re.sub(r"\{\*\}|\{([\w]*)[^}]*\}", lambda m: fill(m) if m.group(0) != "{*}"
                              else "{*}", template)
        if fname in _FORMAT_FUNCS and args:
            # String.format / util.format / fmt.Sprintf: fill %s with the arguments
            fmt = self.evaluate(service, f, args[0], depth + 1, seen)
            rest = iter(args[1:])

            def fill(_m):
                arg = next(rest, None)
                return self.evaluate(service, f, arg, depth + 1, seen) if arg is not None else "{*}"
            return re.sub(r"%[-+ #0-9.]*[sdvfqx]", fill, fmt)
        if node.type == "method_invocation":
            # a.b(...): the method's own return value (a URL-building method in this
            # service), the receiver's value (new ServiceUri("payment", "/x").toUri()),
            # or the arguments (discoveryClient.getInstances("customers-service")) —
            # whichever carries the most concrete text.
            options = [self._lookup(service, fname, depth, seen)]
            obj = node.child_by_field_name("object")
            if obj is not None:
                receiver = self.evaluate(service, f, obj, depth + 1, seen)
                if obj.type in ("object_creation_expression", "new_expression") \
                        and receiver.replace("{*}", ""):
                    # new ServiceUri("payment", ..., "/x").toUri(): the values given at
                    # this site say more than the method's generic body
                    return receiver
                options.append(receiver)
            values = [self.evaluate(service, f, a, depth + 1, seen) for a in args]
            options.append(re.sub(r"(\{\*\})+", "{*}", "".join(values)))
            best = max(options, key=lambda v: len(v.replace("{*}", "")))
            return best if best.replace("{*}", "") else "{*}"
        if fname and fname not in ("URI", "create", "URL", "join", "resolve", "toString",
                                   "Sprintf", "format") and node.type in ("call_expression", "call"):
            known = self._lookup(service, fname, depth, seen)
            if known != "{*}":
                return known
            if fn is not None and fn.type in ("member_expression", "selector_expression", "attribute"):
                obj = fn.child_by_field_name("object") or fn.child_by_field_name("operand")
                if obj is not None and obj.type not in ("identifier",):
                    return self.evaluate(service, f, obj, depth + 1, seen)
        # Builders/constructors: concatenate the evaluated arguments
        # new ServiceUri(new Hostname("payment"), domain, "/paymentAuth") → payment{*}/paymentAuth
        values = [self.evaluate(service, f, a, depth + 1, seen) for a in args
                  if a.type not in ("arrow_function", "function_expression", "lambda", "function")]
        joined = "".join(values)
        joined = re.sub(r"(\{\*\})+", "{*}", joined)
        return joined if joined.replace("{*}", "") else "{*}"

    # ── attach to indexed symbols ────────────────────────────────────────

    def _owner(self, f: _File, line: int) -> tuple[str, str]:
        best = None
        for start, end, node_id, qname in self.symbols.get(f.key, ()):
            if start <= line <= end and (best is None or end - start < best[1] - best[0]):
                best = (start, end, node_id, qname)
        return (best[2], best[3]) if best else ("", "")

    # ── extraction ───────────────────────────────────────────────────────

    def _config_routes(self, service: str, out):
        """API-gateway routes declared in config (Spring Cloud Gateway, Zuul):
        `uri: lb://vets-service` → this service forwards requests to vets-service."""
        root = self.services[service]
        for cfg in list(root.rglob("application*.y*ml")) + list(root.rglob("application*.properties")) \
                + list(root.rglob("bootstrap*.y*ml")):
            if any(p in _SKIP_DIRS or p in ("test",) for p in cfg.relative_to(root).parts):
                continue
            text = cfg.read_text(encoding="utf-8", errors="ignore")
            for m in re.finditer(r"(?:uri|url)\s*[:=]\s*(?:lb|https?)://([\w.-]+)", text):
                target = self.hosts.get(m.group(1).lower().split(".")[0], "")
                if target and target != service:
                    line = text.count("\n", 0, m.start()) + 1
                    out.calls.append(Call(service, "http", "ANY", "", target, str(cfg), line,
                                          "", "", f"route:{m.group(0)}"))
            for m in re.finditer(r"serviceId\s*[:=]\s*([\w.-]+)", text):   # Zuul (placeholder, see below)
                target = self.hosts.get(m.group(1).lower(), "")
                if target and target != service:
                    line = text.count("\n", 0, m.start()) + 1
                    out.calls.append(Call(service, "http", "ANY", "", target, str(cfg), line,
                                          "", "", f"route:{m.group(0)}"))

    def _proxy_routes(self, service: str, out):
        """Reverse-proxy config shipped with a service (nginx): proxy_pass to other services."""
        root = self.services[service]
        for cfg in root.rglob("*"):
            if not cfg.is_file() or not re.search(r"(nginx.*\.conf|\.conf(\.template)?|\.nginx)$", cfg.name):
                continue
            if any(p in _SKIP_DIRS for p in cfg.relative_to(root).parts):
                continue
            text = cfg.read_text(encoding="utf-8", errors="ignore")
            for m in re.finditer(r"^\s*proxy_pass\s+(?:https?://)?([^/;\s]+)", text, re.M):
                host = m.group(1)
                var = re.search(r"\$\{?([A-Za-z_][A-Za-z0-9_]*)\}?", host)
                alias = self._env_host(var.group(1)) if var else host.split(":")[0].lower()
                target = self.hosts.get(alias, "")
                if target and target != service:
                    line = text.count("\n", 0, m.start()) + 1
                    out.calls.append(Call(service, "http", "ANY", "", target, str(cfg), line,
                                          "", "", f"route:proxy_pass {m.group(1)}"))

    def extract(self) -> ServiceContracts:
        out = ServiceContracts()
        grpc_impls = self._grpc_implementations()
        for service in self.files:
            self._config_routes(service, out)
            self._proxy_routes(service, out)
        for service, files in self.files.items():
            for f in files:
                self._http_offers(service, f, out)
                self._calls(service, f, out)
                self._queue_consumers(service, f, out)
            self._grpc_offers(service, files, grpc_impls.get(service, set()), out)
        # de-duplicate
        out.offers = list({(o.service, o.kind, o.method, o.path, o.file, o.line): o
                           for o in out.offers}.values())
        out.calls = list({(c.service, c.kind, c.method, c.path, c.target, c.file, c.line): c
                          for c in out.calls}.values())
        return out

    def _add_offer(self, out, service, f, line, kind, method, path, prefix=False):
        node_id, symbol = self._owner(f, line)
        if symbol in ("", "<module>") and kind == "http":
            # inline handler (app.post('/x', (req, res) => ...)): name it by its route
            symbol = f"{method} {path}"
        out.offers.append(Offer(service, kind, method, path, str(f.path), line,
                                node_id, symbol, prefix))

    def _add_call(self, out, service, f, line, kind, method, path, target, raw):
        node_id, symbol = self._owner(f, line)
        out.calls.append(Call(service, kind, method, path, target, str(f.path), line,
                              node_id, symbol, raw))

    # HTTP offers ---------------------------------------------------------

    def _http_offers(self, service, f: _File, out):
        if f.ext == ".java":
            self._spring_offers(service, f, out)
        for n in _walk(f.root):
            if n.type == "decorator" and f.ext == ".py":
                self._python_route(service, f, n, out)
            if n.type not in ("call_expression", "call"):
                continue
            fn = n.child_by_field_name("function")
            if fn is None:
                continue
            fname = _last_name(f.text(fn))
            args = self._args(n)
            if f.ext == ".go":
                # gorilla / net/http: one route per outermost call chain, e.g.
                # r.Methods("POST").Path("/x").Handler(h) or r.HandleFunc(base+"/x", h).Methods(http.MethodGet)
                if n.parent is not None and n.parent.type not in ("selector_expression",) \
                        and fname in ("Handler", "HandlerFunc", "Methods", "HandleFunc", "Handle",
                                      "Path", "PathPrefix"):
                    self._gorilla_route(service, f, n, out)
                    continue
                if fname in ("HandleFunc", "Handle", "Methods", "Path", "PathPrefix",
                             "Handler", "HandlerFunc"):
                    continue
            if not args:
                continue
            receiver = fn.child_by_field_name("object") or fn.child_by_field_name("operand")
            rtext = f.text(receiver).split(".")[-1] if receiver is not None else ""
            verb = fname.upper()
            route = self.evaluate(service, f, args[0])
            if not route.startswith("/") or len(args) < 2:
                continue
            if verb in HTTP_VERBS + ("ALL", "ANY") and (f.ext != ".go" or fname.isupper()) \
                    and _ROUTE_RECEIVERS.match(rtext or ""):
                # Express app.get / gin r.GET / echo e.GET / chi r.Get
                self._add_offer(out, service, f, n.start_point[0] + 1, "http",
                                verb if verb in HTTP_VERBS else "ANY", normalize_path(route))
            elif f.ext == ".go" and fname in ("Get", "Post", "Put", "Delete", "Patch") \
                    and _ROUTE_RECEIVERS.match(rtext or "") and len(args) >= 2:
                self._add_offer(out, service, f, n.start_point[0] + 1, "http", fname.upper(),
                                normalize_path(route))

    def _chain_has(self, node, names) -> bool:
        p = node.parent
        while p is not None and p.type in ("selector_expression", "call_expression"):
            if p.type == "selector_expression":
                field_ = p.child_by_field_name("field")
                if field_ is not None and field_.text.decode() in names:
                    return True
            p = p.parent
        return False

    def _gorilla_route(self, service, f, n, out):
        methods, path, prefix = [], None, False
        for c in _walk(n):
            if c.type != "call_expression":
                continue
            cfn = c.child_by_field_name("function")
            cname = _last_name(f.text(cfn)) if cfn is not None else ""
            cargs = self._args(c)
            if cname == "Methods":
                methods += [m for m in (self.evaluate(service, f, a).upper() for a in cargs)
                            if m in HTTP_VERBS]   # HEAD/OPTIONS are not separate endpoints
            elif cname in ("Path", "PathPrefix", "HandleFunc", "Handle") and cargs:
                path = self.evaluate(service, f, cargs[0])
                prefix = cname == "PathPrefix"
        if path and path.startswith("{*}/"):
            path = path[3:]        # baseUrl + "/cart": base path set at runtime (usually "")
        if path and path.startswith("/"):
            for m in (methods or ["ANY"]):
                self._add_offer(out, service, f, n.start_point[0] + 1, "http",
                                m if m in HTTP_VERBS else "ANY", normalize_path(path), prefix)

    def _annotations(self, f, decl):
        """[(name, {key: [values]}), ...] for a Java declaration's annotations."""
        result = []
        for child in decl.children:
            if child.type != "modifiers":
                continue
            for a in child.named_children:
                if a.type not in ("annotation", "marker_annotation"):
                    continue
                name = _last_name(f.text(a.child_by_field_name("name")))
                args: dict[str, list] = {}
                arglist = a.child_by_field_name("arguments")
                for arg in (arglist.named_children if arglist is not None else []):
                    if arg.type == "element_value_pair":
                        k = f.text(arg.child_by_field_name("key"))
                        args.setdefault(k, []).append(arg.child_by_field_name("value"))
                    else:
                        args.setdefault("value", []).append(arg)
                result.append((name, args))
        return result

    def _ann_values(self, service, f, nodes) -> list[str]:
        values = []
        for v in nodes or []:
            if v is None:
                continue
            if v.type in ("element_value_array_initializer", "array_initializer"):
                values += [self.evaluate(service, f, x) for x in v.named_children]
            else:
                values.append(self.evaluate(service, f, v))
        return values

    def _spring_offers(self, service, f: _File, out):
        for cls in _walk(f.root):
            if cls.type not in ("class_declaration", "interface_declaration"):
                continue
            prefixes = [""]
            for name, args in self._annotations(f, cls):
                if name == "RequestMapping":
                    vals = self._ann_values(service, f, args.get("value") or args.get("path"))
                    prefixes = [v for v in vals if v.startswith("/")] or [""]
            body = cls.child_by_field_name("body")
            for m in (body.named_children if body is not None else []):
                if m.type != "method_declaration":
                    continue
                for name, args in self._annotations(f, m):
                    if name not in _SPRING_MAPPINGS:
                        continue
                    verb = _SPRING_MAPPINGS[name]
                    if verb == "ANY":
                        for mv in args.get("method", []):
                            mt = f.text(mv).upper()
                            hits = [h for h in HTTP_VERBS if h in mt]
                            verb = hits[0] if len(hits) == 1 else verb
                    paths = self._ann_values(service, f, args.get("value") or args.get("path")) or [""]
                    for prefix in prefixes:
                        for p in paths:
                            full = (prefix.rstrip("/") + "/" + p.lstrip("/")) if p else (prefix or "/")
                            self._add_offer(out, service, f, m.start_point[0] + 1, "http", verb,
                                            normalize_path(full))

    def _python_route(self, service, f, dec, out):
        call = next((c for c in dec.named_children if c.type == "call"), None)
        if call is None:
            return
        fn = call.child_by_field_name("function")
        fname = _last_name(f.text(fn))
        args = self._args(call)
        if not args:
            return
        route = self.evaluate(service, f, args[0])
        if not route.startswith("/"):
            return
        line = dec.parent.start_point[0] + 1 if dec.parent is not None else dec.start_point[0] + 1
        if fname.upper() in HTTP_VERBS:
            self._add_offer(out, service, f, line, "http", fname.upper(), normalize_path(route))
        elif fname in ("route", "api_route", "add_url_rule"):
            methods = [m for m in HTTP_VERBS if m in f.text(call).upper().split("METHODS", 1)[-1]] \
                if "methods" in f.text(call) else ["GET"]
            for m in methods or ["ANY"]:
                self._add_offer(out, service, f, line, "http", m, normalize_path(route))

    # Calls (HTTP + gRPC + queues) ------------------------------------------

    def _calls(self, service, f: _File, out):
        grpc_vars = self._grpc_client_vars(f)
        for n in _walk(f.root):
            if n.type in ("object_creation_expression", "new_expression"):
                ctype = _last_name(f.text(n.child_by_field_name("type") or n.child_by_field_name("constructor")))
                m = re.fullmatch(r"Http(Get|Post|Put|Delete|Patch)", ctype)
                args = self._args(n)
                if m and args:   # Apache HttpClient: new HttpPost(baseUrl + id)
                    template = self.evaluate(service, f, args[0])
                    target, path, looks = parse_url(template, self.hosts)
                    if looks and target and target != service:
                        self._add_call(out, service, f, n.start_point[0] + 1, "http",
                                       m.group(1).upper(), path, target, template)
                continue
            if n.type not in ("call_expression", "call", "method_invocation"):
                continue
            fn = n.child_by_field_name("function") or n.child_by_field_name("name")
            if fn is None:
                continue
            fname = _last_name(f.text(fn))
            line = n.start_point[0] + 1
            if n.type == "method_invocation":
                receiver = n.child_by_field_name("object")
            else:
                receiver = fn.child_by_field_name("object") or fn.child_by_field_name("operand") \
                    if fn.type in ("member_expression", "selector_expression", "attribute") else None
            rtext = f.text(receiver) if receiver is not None else ""

            if self._grpc_call(service, f, n, fname, rtext, grpc_vars, out):
                continue
            if self._queue_producer(service, f, n, fname, rtext, out):
                continue
            if self._is_route_registration(f, fname, rtext) or fname in _URL_BUILDERS:
                continue
            self._http_call(service, f, n, fname, rtext, line, out)

    def _is_route_registration(self, f, fname, rtext) -> bool:
        short = rtext.split(".")[-1] if rtext else ""
        return bool(_ROUTE_RECEIVERS.match(short)) and fname.upper() in HTTP_VERBS + ("ALL", "USE") \
            or fname in ("HandleFunc", "Handle", "Path", "PathPrefix", "Methods")

    def _http_call(self, service, f, n, fname, rtext, line, out):
        args = self._args(n)
        candidates = []   # (template, method)
        method = self._verb_from_chain(fname, rtext) if fname in ("uri", "url") \
            else self._verb_from_name(fname)
        for a in args:
            if a.type == "object":                         # request({uri: ..., method: 'POST'})
                props = {f.text(p.child_by_field_name("key")).strip("'\"`"): p.child_by_field_name("value")
                         for p in a.named_children if p.type == "pair"}
                url_node = props.get("uri") or props.get("url")
                if url_node is not None:
                    m = self.evaluate(service, f, props["method"]).upper() if "method" in props else "GET"
                    candidates.append((self.evaluate(service, f, url_node), m))
            elif a.type == "identifier" and f.ext in (".js", ".ts", ".jsx", ".tsx"):
                obj = self._local_object(f, n, f.text(a))   # var options = {uri:...}; request(options)
                if obj is not None:
                    props = {f.text(p.child_by_field_name("key")).strip("'\"`"): p.child_by_field_name("value")
                             for p in obj.named_children if p.type == "pair"}
                    url_node = props.get("uri") or props.get("url")
                    if url_node is not None:
                        m = self.evaluate(service, f, props["method"]).upper() if "method" in props else "GET"
                        candidates.append((self.evaluate(service, f, url_node), m))
                        continue
                candidates.append((self.evaluate(service, f, a), method))
            elif a.type not in ("arrow_function", "function_expression", "function", "lambda"):
                candidates.append((self.evaluate(service, f, a), method))
        for template, m in candidates:
            target, path, looks = parse_url(template, self.hosts)
            if not looks:
                continue
            hinted = bool(_HTTP_CLIENT_HINT.search(fname + " " + rtext))
            if target == service:
                target = ""  # calls to itself are not cross-service
                if not path:
                    continue
            if not target:
                # Target unknown: only count it when the callee is certainly an
                # HTTP request and the URL has a real path
                if fname not in _HTTP_CALL_NAMES or not path or path == "/":
                    continue
            if m not in HTTP_VERBS:
                m = "GET" if fname == "request" else "ANY"
            self._add_call(out, service, f, line, "http", m, path, target, template)
            break

    def _verb_from_chain(self, fname: str, rtext: str) -> str:
        """Verb of a fluent request: client.get().uri(...) / .method(HttpMethod.POST)."""
        verbs = re.findall(r"\.(get|post|put|delete|patch)\s*\(\s*\)", rtext, re.I)
        if verbs:
            return verbs[-1].upper()
        m = re.search(r"HttpMethod\.(GET|POST|PUT|DELETE|PATCH)", rtext)
        return m.group(1) if m else self._verb_from_name(fname)

    def _verb_from_name(self, fname: str) -> str:
        low = fname.lower()
        for v in HTTP_VERBS:
            if low.startswith(v.lower()) or low.endswith(v.lower()):
                return v
        return "ANY"

    def _local_object(self, f, call_node, name):
        """Object literal assigned to `name` in an enclosing scope of call_node.

        Walks outwards, so `var options = {...}` declared in a handler and used in
        a nested callback (async.waterfall, promises) is found.
        """
        scope = call_node.parent
        while scope is not None:
            if scope.type in ("statement_block", "program", "function_body"):
                for n in _walk(scope):
                    if n.type == "variable_declarator" and f.text(n.child_by_field_name("name")) == name:
                        v = n.child_by_field_name("value")
                        if v is not None and v.type == "object" and n.start_byte < call_node.start_byte:
                            return v
            scope = scope.parent
        return None

    # gRPC ------------------------------------------------------------------

    def _service_for(self, text: str) -> str:
        """'pb.NewCartServiceClient' / 'CartServiceStub' / 'CartServiceGrpc' → 'pkg.CartService'."""
        for short, full in self.proto_by_short.items():
            if re.search(rf"\b(New)?{short}(Client|Stub|Grpc|BlockingStub|FutureStub)?\b", text) \
                    or f".{short}(" in text or text.endswith(f".{short}"):
                return full
        return ""

    def _grpc_client_vars(self, f: _File) -> dict[str, str]:
        """variable/field name → proto service, from client/stub construction."""
        result = {}
        if not self.proto_by_short:
            return result
        for n in _walk(f.root):
            if n.type in ("short_var_declaration", "assignment", "assignment_statement",
                          "variable_declarator", "assignment_expression"):
                left = n.child_by_field_name("left") or n.child_by_field_name("name")
                right = n.child_by_field_name("right") or n.child_by_field_name("value")
                rt = f.text(right)
                if right is None or not re.search(r"(Client|Stub|stub|client)\s*\(", rt) \
                        and not rt.startswith("new "):
                    continue
                svc = self._service_for(rt)
                if svc:
                    result[_last_name(f.text(left).split(",")[0])] = svc
        return result

    def _grpc_call(self, service, f, n, fname, rtext, grpc_vars, out) -> bool:
        if not self.protos or not rtext:
            return False
        svc = ""
        if re.search(r"(New\w+Client|\w+Stub|new\w*Stub)\s*\(", rtext):
            svc = self._service_for(rtext)
        if not svc:
            svc = grpc_vars.get(_last_name(rtext), "")
        if not svc:
            return False
        rpcs = self.protos.get(svc, [])
        rpc = next((r for r in rpcs if r.lower() == fname.lower()), "")
        if not rpc:
            return False
        self._add_call(out, service, f, n.start_point[0] + 1, "grpc", rpc, f"{svc}/{rpc}",
                       "", f"{svc}.{rpc}")
        return True

    def _grpc_implementations(self) -> dict[str, set[str]]:
        """service → proto services it serves (via registration/inheritance)."""
        impls: dict[str, set[str]] = {}
        for service, files in self.files.items():
            for f in files:
                text = f.source.decode("utf-8", errors="ignore")
                for short, full in self.proto_by_short.items():
                    if re.search(rf"Register{short}Server\s*\(|{short}Servicer\b|{short}ImplBase\b|"
                                 rf"\.{short}\.service\b|{short}\.service\b|add_{short}Servicer_to_server",
                                 text):
                        impls.setdefault(service, set()).add(full)
        return impls

    def _grpc_offers(self, service, files, served: set[str], out):
        """Server-side implementations of the rpcs of each proto service `service` serves.

        Java: methods of a class extending XImplBase; Python: methods of a class
        inheriting XServicer; Go: methods (not on *Client types) in the service that
        calls RegisterXServer; Node: handlers passed to addService(X.service, {...}).
        """
        for full in served:
            short = full.split(".")[-1]
            rpcs = {r.lower(): r for r in self.protos.get(full, [])}
            for f in files:
                for n in _walk(f.root):
                    t = n.type
                    if t in ("class_declaration", "class_definition"):
                        head = f.text(n.child_by_field_name("superclass") or n.child_by_field_name("superclasses")
                                      or n.child_by_field_name("interfaces"))
                        if not re.search(rf"{short}(ImplBase|Servicer)\b", head):
                            continue
                        for m in _walk(n.child_by_field_name("body")):
                            if m.type in ("method_declaration", "function_definition"):
                                name = f.text(m.child_by_field_name("name"))
                                if name.lower() in rpcs:
                                    rpc = rpcs[name.lower()]
                                    self._add_offer(out, service, f, m.start_point[0] + 1, "grpc",
                                                    rpc, f"{full}/{rpc}")
                    elif t == "method_declaration" and f.ext == ".go":
                        name = f.text(n.child_by_field_name("name"))
                        recv = f.text(n.child_by_field_name("receiver"))
                        if name.lower() in rpcs and not re.search(r"Client\b", recv):
                            rpc = rpcs[name.lower()]
                            self._add_offer(out, service, f, n.start_point[0] + 1, "grpc", rpc,
                                            f"{full}/{rpc}")
                    elif t in ("call_expression",) and f.ext in (".js", ".ts") \
                            and _last_name(f.text(n.child_by_field_name("function"))) == "addService" \
                            and re.search(rf"\b{short}\.service\b", f.text(n)):
                        for p in _walk(n):
                            if p.type in ("pair", "shorthand_property_identifier"):
                                key = f.text(p.child_by_field_name("key") if p.type == "pair" else p)
                                key = key.strip("'\"")
                                if key.lower() in rpcs:
                                    rpc = rpcs[key.lower()]
                                    line = self._function_line(f, key) or n.start_point[0] + 1
                                    self._add_offer(out, service, f, line, "grpc", rpc, f"{full}/{rpc}")

    def _function_line(self, f: _File, name: str) -> int:
        """Line where a function/method named `name` is defined in this file (Node handlers)."""
        for n in _walk(f.root):
            if n.type in ("function_declaration", "method_definition", "function_definition") \
                    and f.text(n.child_by_field_name("name")) == name:
                return n.start_point[0] + 1
            if n.type == "variable_declarator" and f.text(n.child_by_field_name("name")) == name:
                return n.start_point[0] + 1
        return 0

    # Queues ----------------------------------------------------------------

    def _topic_of(self, service, f, args, keyword_names=("routing_key", "topic", "queue", "QueueUrl",
                                                         "queue_name", "subject")) -> str:
        for a in args:
            if a.type == "keyword_argument":
                if f.text(a.child_by_field_name("name")) in keyword_names:
                    return self.evaluate(service, f, a.child_by_field_name("value"))
        for a in args:
            if a.type in ("keyword_argument",):
                continue
            v = self.evaluate(service, f, a)
            if v and "{*}" not in v and not v.startswith("/"):
                return v
        return ""

    def _queue_producer(self, service, f, n, fname, rtext, out) -> bool:
        if fname not in _PRODUCER_METHODS:
            return False
        if fname in ("send", "publish", "emit", "Publish", "produce", "Produce") and \
                not _QUEUE_RECEIVER_HINT.search(rtext):
            return False
        topic = self._topic_of(service, f, self._args(n))
        if not topic:
            return False
        self._add_call(out, service, f, n.start_point[0] + 1, "queue", "publish", topic, "", topic)
        return True

    def _queue_consumers(self, service, f: _File, out):
        if f.ext == ".java":
            for decl in _walk(f.root):
                if decl.type != "method_declaration":
                    continue
                for name, args in self._annotations(f, decl):
                    keys = _CONSUMER_ANNOTATIONS.get(name)
                    if not keys:
                        continue
                    for k in keys:
                        for topic in self._ann_values(service, f, args.get(k)):
                            if topic and "{*}" not in topic:
                                self._add_offer(out, service, f, decl.start_point[0] + 1,
                                                "queue", "consume", topic)
        for n in _walk(f.root):
            if n.type not in ("call_expression", "call", "method_invocation"):
                continue
            fn = n.child_by_field_name("function") or n.child_by_field_name("name")
            fname = _last_name(f.text(fn)) if fn is not None else ""
            if fname not in _CONSUMER_METHODS:
                continue
            args = self._args(n)
            topics = []
            for a in args:
                if a.type in ("list", "array", "array_initializer"):
                    topics += [self.evaluate(service, f, x) for x in a.named_children]
            topic = self._topic_of(service, f, args, ("queue", "topic", "QueueUrl", "queue_name"))
            if topic:
                topics.append(topic)
            for t in topics:
                if t and "{*}" not in t:
                    self._add_offer(out, service, f, n.start_point[0] + 1, "queue", "consume", t)


def extract_contracts(services: dict[str, Path], symbols=None) -> ServiceContracts:
    """Offers and calls of every service in a system."""
    return ContractExtractor(services, symbols).load().extract()
